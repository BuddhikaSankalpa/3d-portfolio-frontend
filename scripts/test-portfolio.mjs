import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'

const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
await page.route('**/src/main.js', async route => {
    const response = await route.fetch()
    await route.fulfill({ response, body: (await response.text()) + `\nwindow.__portfolio = { scene, camera, controls, modelGroup, get mixers() { return [horseMixer, dogMixer, duckMixer, butterflyMixer, catMixer, rabbitMixer, wavingMixer] } };` })
})
await page.goto(process.env.PORTFOLIO_URL ?? 'http://127.0.0.1:5174/')
await page.waitForSelector('canvas.loaded', { timeout: 120000 })
await page.waitForFunction(() => window.__portfolio.mixers.every(Boolean) && window.__portfolio.modelGroup.children.some(c => c.name === 'Waving yard host'), null, { timeout: 120000 })
await page.waitForFunction(() => performance.getEntriesByType('resource').filter(e => e.name.endsWith('.glb')).length === 10)
const timing = await page.evaluate(() => ({ visible: performance.getEntriesByName('island-visible')[0].startTime, models: performance.getEntriesByType('resource').filter(e => e.name.endsWith('.glb')).map(e => ({ url: e.name, start: e.startTime, bytes: e.encodedBodySize })) }))
assert.equal(timing.models.length, 10)
for (const model of timing.models.filter(m => !m.url.includes('stylized'))) assert.ok(model.start > timing.visible, 'secondary download began before island rendered')
assert.equal(await page.locator('.point.visible').count(), 5)
const times = await page.evaluate(() => window.__portfolio.mixers.map(m => m.time))
await page.waitForTimeout(300)
assert.ok((await page.evaluate(() => window.__portfolio.mixers.map(m => m.time))).every((t,i) => t > times[i]))
const cameraBefore = await page.evaluate(() => window.__portfolio.camera.position.toArray())
await page.mouse.move(1100, 600)
await page.mouse.down()
await page.mouse.move(1200, 650, { steps: 10 })
await page.mouse.up()
await page.waitForTimeout(300)
assert.notDeepEqual(await page.evaluate(() => window.__portfolio.camera.position.toArray()), cameraBefore)
await page.locator('.point-0 .label').click({ force: true })
await page.waitForFunction(() => !document.querySelector('#info-popup').classList.contains('hidden'))
assert.equal(await page.evaluate(() => window.__portfolio.controls.enabled), false)
await page.keyboard.press('Escape')
assert.equal(await page.evaluate(() => window.__portfolio.controls.enabled), true)
await page.locator('#theme-btn').click()
assert.equal(await page.locator('body').evaluate(e => e.classList.contains('light-mode')), true)
await page.locator('#theme-btn').click()
await page.locator('#menu-btn').click()
assert.equal(await page.locator('#menu-btn').getAttribute('aria-expanded'), 'true')
await page.keyboard.press('Escape')
await page.waitForTimeout(1700)
await fs.mkdir('reports', { recursive: true })
await page.screenshot({ path: 'reports/portfolio-optimized.png' })
await fs.writeFile('reports/browser-test.json', JSON.stringify({ timing, errors, passed: ['all ten models decoded', 'secondary requests after island render', 'seven animation mixers advance', 'five markers visible', 'orbit drag', 'marker popup', 'Escape restores controls', 'theme', 'menu'] }, null, 2))
await browser.close()
assert.deepEqual(errors, [])
console.log('Browser interaction, animation, decoding, and loading-order checks passed.')
